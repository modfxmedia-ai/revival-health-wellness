export const getLiveCities = () => CITIES.filter((c) => c.live);
export const getLiveServices = () => SERVICES.filter((s) => s.live);

export const getCity = (slug: string) => CITIES.find((c) => c.slug === slug);
export const getService = (slug: string) =>
  SERVICES.find((s) => s.slug === slug);

export function getLiveAreaPages(): { city: City; service: Service }[] {
  const cities = getLiveCities();
  const services = getLiveServices();
  const pages: { city: City; service: Service }[] = [];
  for (const city of cities) {
    for (const service of services) {
      pages.push({ city, service });
    }
  }
  return pages;
}

export function getNearbyLiveCities(city: City, limit = 5): City[] {
  return city.surroundingCities
    .map((slug) => getCity(slug))
    .filter((c): c is City => Boolean(c && c.live))
    .slice(0, limit);
}

